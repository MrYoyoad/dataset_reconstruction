def _table(s, x, y, col_w, rows, *, header=True, row_h=Inches(0.36), size=11, head_color=C.BLUE,
           colors=None, aligns=None):
    """Native table: rows = list of tuples of str; col_w = list of EMU widths. Returns bottom y."""
    n_cols = len(col_w)
    for r, row in enumerate(rows):
        cy = y + r * row_h
        is_head = header and r == 0
        fill = C.LIGHTBLUE_FILL if is_head else (C.WHITE if r % 2 else C.LIGHTGRAY_FILL)
        cx = x
        for c in range(n_cols):
            H.add_rect(s, cx, cy, col_w[c], row_h, fill_color=fill, line_color=C.LGRAY, line_width=0.5)
            col = head_color if is_head else (colors[r][c] if colors and colors[r] and colors[r][c] else C.BLACK)
            al = aligns[c] if aligns else PP_ALIGN.LEFT
            H.add_text(s, row[c], cx + Inches(0.06), cy, col_w[c] - Inches(0.12), row_h, size=size,
                       bold=is_head, color=col, anchor=MSO_ANCHOR.MIDDLE, align=al)
            cx += col_w[c]
    return y + len(rows) * row_h


def _label(s, text, x, y, w, *, color=C.GRAY, size=C.SZ_SMALL, h=Inches(0.4), bold=False, italic=False):
    return H.add_text(s, text, x, y, w, h, size=size, color=color, bold=bold, italic=italic)


def _bullets(s, items, x, y, w, h, *, size=12, color=C.BLACK, marker="–"):
    return H.add_text(s, "\n".join(f"{marker}  {t}" for t in items), x, y, w, h, size=size, color=color,
                      line_spacing=1.15)


